import {test,expect} from "@playwright/test";

test("Operator reviews actual low-stock, reorder and historical demand evidence",async({page})=>{
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/#inventory");
  await page.getByRole("tab",{name:/Low-stock alerts/}).click();
  const alerts=page.getByRole("region",{name:"Connected low-stock alerts"});
  await alerts.getByLabel("Operator token").fill("wrong");
  await alerts.getByLabel("Sauvignon Blanc 750ml",{exact:true}).check();
  await alerts.getByRole("button",{name:"Review low-stock alerts"}).click();
  await expect(alerts.getByRole("alert")).toContainText("Operator access denied");
  await alerts.getByLabel("Operator token").fill("fixture-test-operator");
  await alerts.getByRole("button",{name:"Review low-stock alerts"}).click();
  await expect(alerts.getByRole("status")).toHaveText("Result: presented");
  await expect(alerts.getByLabel("Inventory decision evidence")).toContainText("low stock");
  await expect(alerts.getByLabel("Agent communication trace")).toContainText("inventory procurement agent");
  await page.getByRole("tab",{name:/Reorder suggestions/}).click();
  const reorder=page.getByRole("region",{name:"Connected reorder suggestions"});
  await reorder.getByLabel("Operator token").fill("fixture-test-operator");
  await reorder.getByLabel("Sauvignon Blanc 750ml",{exact:true}).check();
  await reorder.getByRole("button",{name:"Review reorder suggestions"}).click();
  await expect(reorder.getByRole("status")).toHaveText("Result: presented");
  await expect(reorder.getByLabel("Inventory decision evidence").getByRole("cell",{name:"17",exact:true})).toBeVisible();
  await reorder.getByLabel("Pale Ale 6-pack",{exact:true}).check();
  await reorder.getByRole("button",{name:"Review reorder suggestions"}).click();
  await expect(reorder.getByRole("status")).toHaveText("Result: partial");
  await expect(reorder.getByLabel("Inventory decision evidence")).toContainText("Not calculated");
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:"test-results/reorder-mobile.png",fullPage:true});
  await page.getByRole("link",{name:"Business insights",exact:true}).click();
  await page.getByRole("tab",{name:/Demand trends/}).click();
  const demand=page.getByRole("region",{name:"Connected demand trends"});
  await demand.getByLabel("Business access token").fill("fixture-test-operator");
  await demand.getByRole("button",{name:"Review demand trends"}).click();
  await expect(demand.getByRole("status")).toHaveText("Trend result: complete");
  await expect(demand.getByText("increasing",{exact:true})).toBeVisible();
  await expect(demand.getByLabel("Agent communication trace")).toContainText("business insights agent");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.reload();
  await expect(page.getByLabel("Business access token")).toHaveValue("");
  expect(errors).toEqual([]);
});
